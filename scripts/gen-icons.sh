#!/usr/bin/env bash
# Regenerate the frontend's loaders from its own copy of the MUI icon names.
# Keep the list in sync with steward's scripts/mui-icons.txt when updating MUI.
set -euo pipefail
cd "$(dirname "$0")/.."
version="${MUI_VERSION:-9.5.0}"
{
  echo "// The icons of MUI (@mui/icons-material ${version}) by the names Steward.Icon gives them, each"
  echo "// loaded when it is first drawn. Generated by scripts/gen-icons.sh; do not edit."
  echo "import type { ComponentType } from \"react\";"
  echo "import type { SvgIconProps } from \"@mui/material\";"
  echo
  echo "type Loader = () => Promise<{ default: ComponentType<SvgIconProps> }>;"
  echo
  echo "export const iconLoaders: Record<string, Loader> = {"
  while read -r name; do
    echo "  ${name}: () => import(\"@mui/icons-material/${name}\"),"
  done < scripts/mui-icons.txt
  echo "};"
} > packages/ra-steward/src/icons.generated.ts
